fn main() {
   // part 1 - addition
   let sum = 5550 + 7310;
   println!("The sum of 5550 and 7310 = {}",sum);

   // part 2 - subtraction
   let difference:f32 = 95.5 - 4.3;
   println!("The difference of 95.5 and 4.3 = {}",difference);

   // part 3 - multiplication
   let product:f32 = 4.0 * 30.0;
   println!("The product of 4 and 30 = {}",product);

   // part 4 - division
   let quotient = 56.7 / 32.2;
   println!("56.7 divided by 32.2 is {}",quotient);

   // part 5 - remainder
   let remainder = 43 % 5;
   println!("The remainder of 43 and 5 = {}",remainder);
}
